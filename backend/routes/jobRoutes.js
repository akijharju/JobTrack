const express = require('express');
const pool = require('../db');
const { requireAuth } = require('../auth');

const router = express.Router();

// Check the token before any job route can read or change database records.
router.use(requireAuth);

// Keep validation separate so the update route can reuse it later.
function validateJob(body) {
  // Reject missing bodies and arrays before reading individual fields.
  if (!body || typeof body !== 'object' || Array.isArray(body)) {
    return { error: 'Anna työpaikan tiedot JSON-oliona.' };
  }

  // Reject unsupported fields instead of silently losing user input.
  const allowedFields = ['company', 'title'];

  if (Object.keys(body).some((field) => !allowedFields.includes(field))) {
    return {
      error: 'Tässä vaiheessa sallitut kentät ovat company ja title.',
    };
  }

  // Check types before calling trim, since input may contain any JSON value.
  if (typeof body.company !== 'string' || typeof body.title !== 'string') {
    return {
      error: 'Yritys ja tehtävänimike ovat pakollisia merkkijonoja.',
    };
  }

  // Remove accidental spaces while keeping the original letter case.
  const company = body.company.trim();
  const title = body.title.trim();

  // Count Unicode code points so an emoji does not count as two characters.
  if ([...company].length < 1 || [...company].length > 100) {
    return { error: 'Yrityksen nimen tulee olla 1–100 merkkiä.' };
  }

  if ([...title].length < 1 || [...title].length > 100) {
    return { error: 'Tehtävänimikkeen tulee olla 1–100 merkkiä.' };
  }

  // Return only validated fields that the database operation is allowed to use.
  return { value: { company, title } };
}

router.get('/', async (req, res) => {
  // Filter in SQL so another user's records never reach this response.
  const [jobs] = await pool.execute(
    `SELECT id, company, title
     FROM jobs
     WHERE user_id = ?
     ORDER BY id DESC`,
    [req.user.id]
  );

  // An account without jobs receives an empty array with status 200.
  res.json(jobs);
});

router.post('/', async (req, res) => {
  const validation = validateJob(req.body);

  // Stop before writing anything if the request contains invalid data.
  if (validation.error) {
    return res.status(400).json({ error: validation.error });
  }

  const { company, title } = validation.value;

  // Take ownership from the verified token, never from the request body.
  const [result] = await pool.execute(
    'INSERT INTO jobs (user_id, company, title) VALUES (?, ?, ?)',
    [req.user.id, company, title]
  );

  // Return the saved fields and the ID generated by MariaDB.
  return res.status(201).json({
    id: result.insertId,
    company,
    title,
  });
});

module.exports = router;